package dev.quinton.goa.core.game.puzzles.rounds

import dev.quinton.goa.core.game.puzzles.GoalState
import dev.quinton.goa.core.game.puzzles.Node
import dev.quinton.goa.core.game.puzzles.PuzzleSolver
import dev.quinton.goa.core.game.puzzles.Side
import dev.quinton.goa.core.game.puzzles.Value

/**
 * Depth-first proof-number search (df-pn, Nagai 2002) over a puzzle's AND-OR tree, for proving full
 * rounds in tests (ENCODING.md "Full rounds"). The game is a DAG, so sums are the weak form (WPNS,
 * Ueda 2008: largest child + the number of others), and thresholds use the 1+ε trick (Pawlewicz & Lew
 * 2007) to re-expand less. Children are generated by the engine each time a node is entered, so
 * [engineRuns] is the real cost; [entries] counts distinct positions.
 *
 * A proof found here is only trusted after [verify] has replayed it through the engine.
 */
class DfPn(
    private val solver: PuzzleSolver,
    private val maxEngineRuns: Long,
    tableBits: Int = 22,
    private val deadlineNanos: Long = Long.MAX_VALUE,
    /** A penalty per choice at a player node (added to its first proof number), or null for none. */
    private val order: ((Node, List<Int>) -> IntArray)? = null,
) {
    private val mask = (1 shl tableBits) - 1
    private val k1 = LongArray(1 shl tableBits)
    private val k2 = LongArray(1 shl tableBits)
    private val pns = IntArray(1 shl tableBits)
    private val dns = IntArray(1 shl tableBits)

    var engineRuns = 0L
        private set
    var entries = 0
        private set
    var visits = 0L
        private set
    private var exhausted = false

    private fun slot(a: Long, b: Long): Int {
        var i = (a xor (a ushr HASH_SHIFT)).toInt() and mask
        while (true) {
            if (k1[i] == 0L && k2[i] == 0L) return i
            if (k1[i] == a && k2[i] == b) return i
            i = (i + 1) and mask
        }
    }

    private fun keyA(n: Node): Long = (n.checkpointHash xor (n.session.stepAnswers.hashCode() * KEY_MUL)) or 1L

    private fun keyB(n: Node): Long = n.checkpointHash2 + n.session.stepAnswers.hashCode() + n.progress.coins * KEY_MUL

    private class Kid(val index: Int, val node: Node, val a: Long, val b: Long, var pn: Int, var dn: Int)

    private fun terminal(n: Node): Value? = when {
        n.progress.state == GoalState.MET -> Value.WIN
        n.progress.state == GoalState.FAILED -> Value.LOSS
        n.decision == null -> Value.LOSS
        else -> null
    }

    /** Proves or disproves from [root]; UNKNOWN when a budget ran out. */
    fun solve(root: Node): Value {
        terminal(root)?.let { return it }
        mid(root, INF, INF)
        val i = slot(keyA(root), keyB(root))
        return when {
            pns[i] == 0 -> Value.WIN
            dns[i] == 0 -> Value.LOSS
            else -> Value.UNKNOWN
        }
    }

    private fun kid(n: Node, index: Int): Kid {
        val d = n.decision!!
        engineRuns++
        val c = checkNotNull(solver.child(n, d.options[index]))
        return when (terminal(c)) {
            Value.WIN -> Kid(index, c, 0, 0, 0, INF)

            Value.LOSS, Value.UNKNOWN -> Kid(index, c, 0, 0, INF, 0)

            null -> {
                val a = keyA(c)
                val b = keyB(c)
                val i = slot(a, b)
                if (k1[i] == a && k2[i] == b) {
                    Kid(index, c, a, b, pns[i], dns[i])
                } else {
                    val width = solver.choices(c).size
                    val or = solver.sideOf(c.decision!!) != Side.OPPONENT
                    Kid(index, c, a, b, if (or) 1 else width, if (or) width else 1)
                }
            }
        }
    }

    private fun store(a: Long, b: Long, pn: Int, dn: Int) {
        val i = slot(a, b)
        if (k1[i] == 0L && k2[i] == 0L) {
            k1[i] = a
            k2[i] = b
            entries++
            if (entries > mask / 10 * 8) exhausted = true
        }
        pns[i] = pn
        dns[i] = dn
    }

    private fun outOfBudget(): Boolean {
        if (exhausted || engineRuns >= maxEngineRuns) return true
        if (visits and CLOCK_MASK == 0L && System.nanoTime() > deadlineNanos) exhausted = true
        return exhausted
    }

    @Suppress("CyclomaticComplexMethod", "LongMethod", "NestedBlockDepth")
    private fun mid(n: Node, thPn: Int, thDn: Int) {
        visits++
        val a = keyA(n)
        val b = keyB(n)
        val d = n.decision!!
        val or = solver.sideOf(d) != Side.OPPONENT
        val choices = solver.choices(n)
        val kids = choices.mapTo(ArrayList(choices.size)) { kid(n, it) }
        if (or && order != null && kids.size > 1) {
            val bias = order.invoke(n, choices)
            kids.forEachIndexed { i, k ->
                if (k.pn in 1 until INF && k.dn in 1 until INF && !seen(k)) k.pn += bias[i]
            }
        }
        while (true) {
            // The node's numbers from its children (OR: min pn, weak sum dn; AND: mirrored).
            var minP = INF
            var second = INF
            var best = -1
            var maxD = 0
            var open = 0
            kids.forEachIndexed { i, k ->
                val p = if (or) k.pn else k.dn
                val q = if (or) k.dn else k.pn
                if (p < minP) {
                    second = minP
                    minP = p
                    best = i
                } else if (p < second) {
                    second = p
                }
                if (p != INF) {
                    if (q > maxD) maxD = q
                    open++
                }
            }
            val sum = when {
                minP == 0 -> INF
                open == 0 -> 0
                else -> minOf(INF.toLong(), maxD.toLong() + open - 1).toInt()
            }
            val pn = if (or) minP else sum
            val dn = if (or) sum else minP
            store(a, b, pn, dn)
            if (pn >= thPn || dn >= thDn || pn == 0 || dn == 0 || outOfBudget()) return
            val k = kids[best]
            val thMin = if (or) thPn else thDn
            val thSum = if (or) thDn else thPn
            val others = if (or) dn else pn
            val own = if (or) k.dn else k.pn
            val childMin = minOf(thMin.toLong(), (second.toLong() * EPS_NUM / EPS_DEN) + 1).toInt()
            val childSum = minOf(INF.toLong(), thSum.toLong() - others + own).toInt()
            if (or) mid(k.node, childMin, childSum) else mid(k.node, childSum, childMin)
            val i = slot(k.a, k.b)
            k.pn = pns[i]
            k.dn = dns[i]
        }
    }

    private fun seen(k: Kid): Boolean {
        val i = slot(k.a, k.b)
        return k1[i] == k.a && k2[i] == k.b
    }

    /** True when the table (or the goal itself) says [n] is proven. */
    fun proven(n: Node): Boolean = when (terminal(n)) {
        Value.WIN -> true

        Value.LOSS, Value.UNKNOWN -> false

        null -> {
            val i = slot(keyA(n), keyB(n))
            k1[i] == keyA(n) && k2[i] == keyB(n) && pns[i] == 0
        }
    }

    /** What a proof looks like after it has been replayed through the engine. */
    class Proof(
        val positions: Int,
        val playerPositions: Int,
        val edges: Long,
        val enemyPositions: Int,
        val moves: Map<Pair<Long, Long>, Int>,
    )

    /**
     * Walks the proof from [root] with the real engine: at a player or friend node the first child
     * proven by the table, at an enemy node every choice. Null when a claimed proof doesn't hold.
     */
    fun verify(root: Node): Proof? {
        val done = HashSet<Pair<Long, Long>>()
        val moves = HashMap<Pair<Long, Long>, Int>()
        var edges = 0L
        var enemy = 0
        var ok = true

        fun go(n: Node) {
            when (terminal(n)) {
                Value.WIN -> return

                Value.LOSS, Value.UNKNOWN -> {
                    ok = false
                    return
                }

                null -> Unit
            }
            val k = keyA(n) to keyB(n)
            if (!done.add(k)) return
            val d = n.decision!!
            if (solver.sideOf(d) == Side.OPPONENT) {
                enemy++
                for (i in solver.choices(n)) {
                    edges++
                    go(checkNotNull(solver.child(n, d.options[i])))
                    if (!ok) return
                }
            } else {
                val pick = solver.choices(n).firstNotNullOfOrNull { i ->
                    edges++
                    val c = checkNotNull(solver.child(n, d.options[i]))
                    if (proven(c)) i to c else null
                }
                if (pick == null) {
                    ok = false
                    return
                }
                moves[k] = pick.first
                go(pick.second)
            }
        }
        go(root)
        return if (ok) Proof(done.size, moves.size, edges, enemy, moves) else null
    }

    companion object {
        const val INF: Int = 1_000_000_000
        private const val HASH_SHIFT = 31
        private const val KEY_MUL = -0x61c8864680b583ebL
        private const val EPS_NUM = 5L
        private const val EPS_DEN = 4L
        private const val CLOCK_MASK = 0xFFFL
    }
}
