/** Writes `catalog/index.json`, `catalog/heroes/<id>.json` and `official/SOURCES.md`. */
class Output(private val assetsDir: File) {
    @OptIn(ExperimentalSerializationApi::class)
    private val json = Json {
        prettyPrint = true
        prettyPrintIndent = "  "
        encodeDefaults = true
        explicitNulls = true
    }

    private val catalogDir = File(assetsDir, "catalog")
    private val heroesDir = File(catalogDir, "heroes")

    /** Writes catalog JSON; bumps `dataVersion` only when a generated file changes. Returns it. */
    fun writeCatalog(result: ImportResult): Int {
        val heroFiles = result.heroes.associate { "${it.id}.json" to json.encodeToString(Hero.serializer(), it) + "\n" }
        val indexFile = File(catalogDir, "index.json")
        val previous = indexFile.takeIf {
            it.isFile
        }?.let { json.decodeFromString(CatalogIndex.serializer(), it.readText()) }
        fun indexText(version: Int) = json.encodeToString(
            CatalogIndex.serializer(),
            CatalogIndex(version, Importer.PRINTING, result.products, result.heroes.map { it.id }),
        ) + "\n"
        val existingHeroes = heroesDir.listFiles { f -> f.extension == "json" }.orEmpty().associate {
            it.name to
                it.readText()
        }
        val version = when {
            previous == null -> 1

            existingHeroes != heroFiles || indexText(previous.dataVersion) != indexFile.readText() ->
                previous.dataVersion +
                    1

            else -> previous.dataVersion
        }
        heroesDir.mkdirs()
        existingHeroes.keys.filter { it !in heroFiles }.forEach { File(heroesDir, it).delete() }
        heroFiles.forEach { (name, text) -> File(heroesDir, name).writeText(text) }
        indexFile.writeText(indexText(version))
        return version
    }

    fun writeSources(
        result: ImportResult,
        documents: List<PinnedDocument> = emptyList(),
        rulebookImages: Pair<PinnedDocument, List<RulebookImage>>? = null,
    ) {
        val sb = StringBuilder()
        sb.appendLine("# Official assets — sources")
        sb.appendLine()
        sb.appendLine("Generated by `tools/catalog-import`; do not edit. Content © Wolff Designa, bundled for a")
        sb.appendLine("private, non-commercial build only (ADR-006). Each file was downscaled and re-encoded as")
        sb.appendLine(
            "WebP q${ImageIo.QUALITY} (cards ≤ ${ImageIo.CARD_MAX_EDGE} px, " +
                "portraits ≤ ${ImageIo.PORTRAIT_MAX_EDGE} px, deck symbols ≤ $SYMBOL_MAX_EDGE px, " +
                "item icons ≤ $ITEM_ICON_MAX_EDGE px on the long edge; rulebook graphics at their own size).",
        )
        sb.appendLine()
        sb.appendLine(
            "Deck symbols (`official/heroes/<id>/symbol.webp`) are source 1's hero logos, each accepted only",
        )
        sb.appendLine(
            "when it matches its own hero's card back best among all card backs (REPORT.md, \"Deck symbols\").",
        )
        sb.appendLine()
        sb.appendLine("| Source | Commit |")
        sb.appendLine("|---|---|")
        result.assetSources.values.map { it.source }.distinctBy { it.id }
            .forEach { sb.appendLine("| https://github.com/${it.repo} | `${it.sha}` |") }
        sb.appendLine()
        if (documents.isNotEmpty()) {
            sb.appendLine(
                "Verbatim rules text in `catalog/rules-reference.json` (hand-picked excerpts, checked against",
            )
            sb.appendLine("the document by `--rules-only`):")
            sb.appendLine()
            sb.appendLine("| Document | URL | SHA-256 |")
            sb.appendLine("|---|---|---|")
            documents.forEach { sb.appendLine("| ${it.name} | ${it.url} | `${it.sha256}` |") }
            sb.appendLine()
        }
        sb.appendLine("| File | Source |")
        sb.appendLine("|---|---|")
        result.assetSources.toSortedMap().forEach { (out, src) ->
            sb.appendLine("| `$out` | ${src.source.rawUrl(src.path)} |")
        }
        if (rulebookImages != null) {
            val (doc, images) = rulebookImages
            sb.appendLine()
            sb.appendLine(
                "Graphics extracted from the rulebook PDF (SHA-256 `${doc.sha256}`), by PDF page and image object:",
            )
            sb.appendLine()
            sb.appendLine("| File | Page (printed) | PDF page · object | What |")
            sb.appendLine("|---|---|---|---|")
            images.sortedBy { it.out }.forEach {
                sb.appendLine("| `${it.out}` | p.${it.printedPage} | ${it.pdfPage} · ${it.obj} | ${it.what} |")
            }
        }
        File(assetsDir, "official").mkdirs()
        File(assetsDir, "official/SOURCES.md").writeText(sb.toString())
    }
}

/** Writes `tools/catalog-import/REPORT.md`. */
class ReportWriter(
    private val result: ImportResult,
    private val version: Int,
    private val lock: SourcesLock,
    private val overrides: Overrides,
) {
    private val sb = StringBuilder()
    private val heroes = result.heroes

    fun write(file: File) {
        sb.appendLine("# Catalog import report")
        sb.appendLine()
        sb.appendLine("Generated by `./gradlew :tools:catalog-import:run`; do not edit. `dataVersion` $version.")
        sb.appendLine()
        sources()
        counts()
        verified()
        disagreements()
        overridesApplied()
        crossCheckGaps()
        missingFields()
        images()
        deckSymbols()
        printedMarks()
        notRepresentable()
        file.writeText(sb.toString())
    }

    private fun line(text: String = "") {
        sb.appendLine(text)
    }

    private fun sources() {
        line("## Sources")
        lock.sources.forEach {
            line("- **${it.name}** `${it.repo}` @ `${it.sha.take(12)}` (pinned ${it.pinned}) — ${it.use}")
        }
        line()
    }

    private fun countRow(label: String, hs: List<Hero>) {
        val images = hs.sumOf { h -> h.allCards.count { it.image != null } }
        line(
            "| $label | ${hs.size} | ${hs.sumOf { it.cards.size }} | ${hs.count { it.handicap != null }} | " +
                "${hs.sumOf { it.extras.size }} | $images | ${hs.count { it.verified }} |",
        )
    }

    private fun counts() {
        line("## Counts per product")
        line("| Product | Heroes | Deck cards | Handicap | Extras | Card images | Verified |")
        line("|---|---|---|---|---|---|---|")
        result.products.forEach { p -> countRow(p.name, heroes.filter { it.product == p.id }) }
        countRow("**Total**", heroes)
        line()
    }

    private fun verified() {
        val reports = result.reports.associateBy { it.heroId }
        line("## Verified")
        line("Rule (docs/DOMAIN.md#sources): numbers agree between source 1 and colefin8 (or the card images),")
        line("text agrees between source 1 and goa2-faq, and every disagreement is resolved in `overrides.json`.")
        line()
        line("| Hero | Verified | Why |")
        line("|---|---|---|")
        heroes.forEach { h ->
            val mark = if (h.verified) "yes" else "**no**"
            line("| ${h.displayName} (`${h.id}`) | $mark | ${reports[h.id]?.verifiedBecause} |")
        }
        line()
    }

    private fun disagreements() {
        val unresolved = result.reports.flatMap { it.unresolved }
        line("## Unresolved disagreements (${unresolved.size})")
        if (unresolved.isEmpty()) line("None.")
        unresolved.groupBy { it.heroId }.forEach { (hero, list) ->
            line("### $hero")
            list.forEach { line("- " + describe(it)) }
        }
        line()
        val resolved = result.reports.flatMap { it.disagreements - it.unresolved.toSet() }
        line("## Disagreements resolved in overrides.json (${resolved.size})")
        resolved.forEach { d ->
            val entry = overrides.heroes[d.entity] ?: overrides.cards[d.entity]
            line("- ${describe(d)} — evidence: ${entry.string("evidence")}")
        }
        line()
    }

    private fun overridesApplied() {
        line("## Overrides applied")
        (overrides.heroes + overrides.cards).forEach { (id, o) ->
            val keys = o.keys.filterNot { it in Overrides.META }.joinToString().ifEmpty { "—" }
            val confirmed = o["confirm"]?.let { " (confirmed: $it)" }.orEmpty()
            line("- `$id`: $keys$confirmed — ${o.string("reason")}")
        }
        overrides.imageChecks.forEach { (id, c) ->
            line("- `$id`: numbers checked against card images (${c.checked}) — ${c.evidence}")
        }
        line("- ${overrides.images.size} card image(s) assigned by hand (`images`).")
        line()
    }

    private fun crossCheckGaps() {
        line("## Cards missing from a cross-check source")
        result.reports.forEach { r ->
            when {
                !r.numbers.present -> line("- `${r.heroId}`: not in colefin8 (numbers unchecked by that source)")

                r.numbers.unmatched.isNotEmpty() -> line(
                    "- `${r.heroId}`: not matched in colefin8: ${r.numbers.unmatched.joinToString()}",
                )
            }
            when {
                !r.texts.present -> line("- `${r.heroId}`: not in goa2-faq")

                r.texts.unmatched.isNotEmpty() -> line(
                    "- `${r.heroId}`: not matched in goa2-faq: ${r.texts.unmatched.joinToString()}",
                )
            }
        }
        line()
    }

    private fun missingFields() {
        line("## Missing fields (null)")
        line("Expected nulls (not listed): tier of basic/Handicap cards; values a card does not print;")
        line(
            "initiative and primary action of Ultimates; initiative of spellbook pages " +
                "(a spell is cast with Gydion's card).",
        )
        val missing = heroes.flatMap { h ->
            buildList {
                if (h.complexity == null) add("${h.id}: complexity")
                if (h.portrait == null) add("${h.id}: portrait")
                if (h.lore == null) add("${h.id}: lore")
                if (h.faq.isEmpty()) add("${h.id}: no FAQ rulings in goa2-faq")
                // Spellbook pages (extras) print no initiative.
                (h.cards + listOfNotNull(h.handicap)).filter {
                    it.color !in NO_INITIATIVE && it.initiative == null
                }.forEach { add("${it.id}: initiative") }
                h.allCards.filter { it.text.isBlank() }.forEach { add("${it.id}: text") }
            }
        }
        if (missing.isEmpty()) line("\nNone.") else missing.forEach { line("- $it") }
        line()
    }

    private fun images() {
        line("## Images")
        val missingImages = result.reports.flatMap { r -> r.missingImages }
        line("Missing card images: ${if (missingImages.isEmpty()) "none" else missingImages.joinToString()}.")
        line()
        line("Card scans are identified by comparing each scan's illustration with source-1 artwork;")
        line("Handicap cards sharing their basic card's art are told apart by the top-right badge.")
        line("Low-confidence matches (second-best / best distance < ${Importer.LOW_CONFIDENCE}) — check visually:")
        val low = result.reports.flatMap { r ->
            r.imageMatches.filter {
                it.confidence < Importer.LOW_CONFIDENCE && it.method == "art"
            }.map { r.heroId to it }
        }
        if (low.isEmpty()) line("\nNone.")
        low.forEach { (h, m) ->
            line("- `$h` ${m.art} ← ${m.scan.substringAfterLast('/')} (confidence ${"%.2f".format(m.confidence)})")
        }
        result.reports.flatMap { r -> r.notes.map { "`${r.heroId}`: $it" } }.forEach { line("- $it") }
        line()
    }

    private fun deckSymbols() {
        val checks = result.symbolChecks
        line("## Deck symbols")
        line(
            "Source 1's logo for each hero against every hero's card back (last scan in source 2): accepted when its",
        )
        line(
            "own card back is the nearest, by a margin of at least ${DeckSymbols.MIN_MARGIN}× over the next. " +
                "${checks.count { it.pass }} of ${checks.size} accepted.",
        )
        val failed = checks.filterNot { it.pass }
        if (failed.isEmpty()) line("\nNone rejected.")
        failed.forEach {
            line("- `${it.heroId}`: nearest card back `${it.nearest}`, margin ${"%.2f".format(it.margin)} (no symbol)")
        }
        val lowest = checks.filter { it.pass }.minByOrNull { it.margin }
        if (lowest != null) line("\nLowest accepted margin: `${lowest.heroId}` ${"%.2f".format(lowest.margin)}.")
        line()
    }

    private fun printedMarks() {
        val cards = heroes.flatMap { it.allCards }
        val plus = cards.filter { it.values.plus.isNotEmpty() }
        line("## Printed `+` values and bold keywords")
        line(
            "- ${cards.count { CardText.STRONG in it.text }} card(s) have bold keywords (`**…**`, from source 1).",
        )
        line(
            "- ${plus.size} card(s) print a value with `+` (`values.plus`; the value grows per the card text). " +
                "Cross-checked against colefin8's `4+` notation (field `values.plus`):",
        )
        plus.forEach { card ->
            val printed = card.values.plus.joinToString { "${it.name.lowercase()} ${card.values.get(it)}+" }
            line("  - `${card.id}` ${card.name}: $printed")
        }
        line()
    }

    private fun notRepresentable() {
        line("## Not representable in the schema")
        if (result.unknownIcons.isEmpty()) line("None.")
        if (result.unknownIcons.isNotEmpty()) {
            line(
                "- Unknown icon tokens (left as text): ${result.unknownIcons.joinToString()}",
            )
        }
    }

    private fun JsonObject?.string(key: String): String = this?.get(key)?.toString()?.trim('"').orEmpty()

    private fun describe(d: Disagreement): String {
        val show = { s: String -> if (s.length > MAX_SHOWN) s.take(MAX_SHOWN) + "…" else s }
        return if (d.field == "text") {
            "`${d.entity}` text differs from ${d.source}: ${TextMarkup.describeDifference(d.primary, d.other)}"
        } else {
            "`${d.entity}` ${d.field}: source 1 = `${show(d.primary)}`, ${d.source} = `${show(d.other)}`"
        }
    }

    private companion object {
        const val MAX_SHOWN = 160
        val NO_INITIATIVE = setOf(CardColor.PURPLE, CardColor.OTHER)
    }
}
