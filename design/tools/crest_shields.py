"""Compose the 24 player crests as filled heraldic shields (opus #29, round 2 of the UI hill climb).

Usage (from the repo root):
    python -P -E design/tools/crest_shields.py           # write design/crests/crest_NN.svg
    python -P -E design/tools/crest_shields.py --check   # fail if any shield master is stale

The charge (the glyph) of each crest stays its line master in design/avatars/crest_NN.svg (the web app
draws those, tinted). This script sets each charge on a shield in the game's icon style: a dark outline,
a metal rim, a metal field lit from the left, and the charge in dark ink with a light emboss under it.
Fields alternate so neighbouring crests differ at a glance: even crests are a bronze field in a steel rim,
odd ones a steel field in a bronze rim. Neither metal is a team colour (ADR-070): red and blue stay the
teams' alone. design/tools/svg2vd.py turns the shields into core/designsystem drawables crest_NN.xml.
"""

import os
import sys
import xml.etree.ElementTree as ET

SVG_NS = "http://www.w3.org/2000/svg"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CHARGES = os.path.join(ROOT, "design", "avatars")
OUT = os.path.join(ROOT, "design", "crests")

# The heater shield, outside in: outline, rim, a dark line, the field.
OUTLINE = "M2.2 1.2H21.8V10.6C21.8 16.8 17.6 21 12 23.4C6.4 21 2.2 16.8 2.2 10.6Z"
RIM = "M3.2 2.2H20.8V10.6C20.8 16.2 17 20 12 22.2C7 20 3.2 16.2 3.2 10.6Z"
LINE = "M4.6 3.6H19.4V10.6C19.4 15.4 16.2 18.7 12 20.6C7.8 18.7 4.6 15.4 4.6 10.6Z"
FIELD = "M5.1 4.1H18.9V10.6C18.9 15.1 15.9 18.2 12 20C8.1 18.2 5.1 15.1 5.1 10.6Z"
# Heraldic light: the dexter (left) half of the field a shade brighter, the rim's top catching light.
SHEEN = "M5.1 4.1H12V20C8.1 18.2 5.1 15.1 5.1 10.6Z"
GLINT = "M3.2 2.2H20.8V3.1H3.2Z"

OUTLINE_INK = "#15181C"
LINE_INK = "#2A2520"
INK = "#1B1712"
EMBOSS = "#FFF4D6"

BRONZE = ("#F0D394", "#C9A35B", "#8E6A2C")
STEEL = ("#EEF2F5", "#B7C1CA", "#6E7B87")

# The charge in an 11 x 11 box centred a little above the field's middle; strokes thickened to read on metal.
SCALE = 0.56
CENTRE = (12.0, 11.4)
STROKE = 3.2
HEAVY_STROKE = 4.2


def gradient(gid, stops, x1, y1, x2, y2):
    s = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in stops)
    return (
        f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">'
        f"{s}</linearGradient>"
    )


def charge(path):
    """The charge's title and its shapes as markup, white made ink and thick strokes made heavier."""
    tree = ET.parse(path)
    root = tree.getroot()
    title = None
    shapes = []
    for child in root:
        tag = child.tag.replace("{" + SVG_NS + "}", "")
        if tag == "title":
            title = child.text
            continue
        child.tail = None
        if child.attrib.get("stroke-width") == "3":
            child.attrib["stroke-width"] = str(HEAVY_STROKE)
        for k in ("fill", "stroke"):
            if child.attrib.get(k) == "#FFFFFF":
                child.attrib[k] = "COLOUR"
        markup = ET.tostring(child, encoding="unicode").replace(f' xmlns:ns0="{SVG_NS}"', "")
        markup = markup.replace("ns0:", "")
        shapes.append(markup)
    return title, shapes


def shield(index, title, shapes):
    bronze_field = index % 2 == 0
    field = BRONZE if bronze_field else STEEL
    rim = STEEL if bronze_field else BRONZE
    tx = CENTRE[0] - 12 * SCALE
    ty = CENTRE[1] - 12 * SCALE
    name = title.split(":", 1)[1].strip() if title and ":" in title else f"Crest {index:02d}"
    metal = "bronze field, steel rim" if bronze_field else "steel field, bronze rim"

    def charge_group(colour, dy, opacity=None):
        op = f' opacity="{opacity}"' if opacity else ""
        body = "\n    ".join(s.replace("COLOUR", colour) for s in shapes)
        return (
            f'  <g transform="translate({tx:g} {ty + dy:g}) scale({SCALE:g})" fill="none" stroke="{colour}" '
            f'stroke-width="{STROKE:g}" stroke-linecap="round" stroke-linejoin="round"{op}>\n    {body}\n  </g>'
        )

    defs = "\n    ".join(
        [
            gradient("rim", [(0, rim[0]), (0.45, rim[1]), (1, rim[2])], 12, 2.2, 12, 22.2),
            gradient("field", [(0, field[0]), (0.5, field[1]), (1, field[2])], 12, 4.1, 12, 20),
        ]
    )
    return "\n".join(
        [
            f'<svg xmlns="{SVG_NS}" viewBox="0 0 24 24" width="24" height="24">',
            f"  <title>Crest {index:02d}: {name} on a shield ({metal}). Generated by design/tools/crest_shields.py"
            f" from design/avatars/crest_{index:02d}.svg.</title>",
            f"  <defs>\n    {defs}\n  </defs>",
            f'  <path d="{OUTLINE}" fill="{OUTLINE_INK}"/>',
            f'  <path d="{RIM}" fill="url(#rim)"/>',
            f'  <path d="{GLINT}" fill="#FFFFFF" opacity="0.35"/>',
            f'  <path d="{LINE}" fill="{LINE_INK}"/>',
            f'  <path d="{FIELD}" fill="url(#field)"/>',
            f'  <path d="{SHEEN}" fill="#FFFFFF" opacity="0.14"/>',
            charge_group(EMBOSS, 0.45, 0.55),
            charge_group(INK, 0),
            "</svg>",
            "",
        ]
    )


def blank():
    """The shield with no charge: the face for a player without a crest (their initial goes on it)."""
    defs = "\n    ".join(
        [
            gradient("rim", [(0, STEEL[0]), (0.45, STEEL[1]), (1, STEEL[2])], 12, 2.2, 12, 22.2),
            gradient("field", [(0, STEEL[0]), (0.5, STEEL[1]), (1, STEEL[2])], 12, 4.1, 12, 20),
        ]
    )
    return "\n".join(
        [
            f'<svg xmlns="{SVG_NS}" viewBox="0 0 24 24" width="24" height="24">',
            "  <title>Blank crest: a steel shield with no charge, for a player's initial. Generated by"
            " design/tools/crest_shields.py.</title>",
            f"  <defs>\n    {defs}\n  </defs>",
            f'  <path d="{OUTLINE}" fill="{OUTLINE_INK}"/>',
            f'  <path d="{RIM}" fill="url(#rim)"/>',
            f'  <path d="{GLINT}" fill="#FFFFFF" opacity="0.35"/>',
            f'  <path d="{LINE}" fill="{LINE_INK}"/>',
            f'  <path d="{FIELD}" fill="url(#field)"/>',
            f'  <path d="{SHEEN}" fill="#FFFFFF" opacity="0.14"/>',
            "</svg>",
            "",
        ]
    )


def outputs():
    names = sorted(f for f in os.listdir(CHARGES) if f.startswith("crest_") and f.endswith(".svg"))
    for f in names:
        index = int(f[len("crest_"):-4])
        title, shapes = charge(os.path.join(CHARGES, f))
        yield os.path.join(OUT, f), shield(index, title, shapes)
    yield os.path.join(OUT, "crest_blank.svg"), blank()


def main():
    check = "--check" in sys.argv
    stale = []
    for path, svg in outputs():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == svg:
            continue
        if check:
            stale.append(path)
            continue
        os.makedirs(OUT, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(svg)
        print("wrote", os.path.relpath(path, ROOT))
    if stale:
        print("stale:", *stale, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
