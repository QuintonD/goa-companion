package dev.quinton.goa.web.ui

import dev.quinton.goa.web.ui.SimpleMarkdown.Block
import dev.quinton.goa.web.ui.SimpleMarkdown.Inline
import kotlin.test.Test
import kotlin.test.assertEquals

class SimpleMarkdownTest {
    @Test
    fun readsTheShapeOfSourcesMd() {
        val md = """
            # Official assets — sources

            Generated by `tools/catalog-import`; do not edit.
            Content © Wolff Designa.

            | Source | Commit |
            |---|---|
            | https://github.com/dmrediger/goa2 | `23544c3a` |
            | https://github.com/yvo-niedrich/goa2-faq | `b841b76c` |
            Verbatim rules text follows.
        """.trimIndent()
        assertEquals(
            listOf(
                Block.Heading(1, "Official assets — sources"),
                Block.Paragraph("Generated by `tools/catalog-import`; do not edit. Content © Wolff Designa."),
                Block.Table(
                    listOf("Source", "Commit"),
                    listOf(
                        listOf("https://github.com/dmrediger/goa2", "`23544c3a`"),
                        listOf("https://github.com/yvo-niedrich/goa2-faq", "`b841b76c`"),
                    ),
                ),
                Block.Paragraph("Verbatim rules text follows."),
            ),
            SimpleMarkdown.parse(md),
        )
    }

    @Test
    fun inlineCodeAndBareLinks() {
        assertEquals(
            listOf(
                Inline.Plain("See "),
                Inline.CodeSpan("official/x.webp"),
                Inline.Plain(" from "),
                Inline.Link("https://example.org/a.jpeg"),
                Inline.Plain("."),
            ),
            SimpleMarkdown.inline("See `official/x.webp` from https://example.org/a.jpeg."),
        )
    }
}
