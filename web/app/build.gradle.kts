/**
 * Turns the production distribution into the deployable site: drops source maps, stamps the build
 * id (a hash of every file) into index.html and sw.js, and writes `asset-manifest.json` (path, size,
 * hash of each file) that the service worker precaches from and the offline download reads.
 */
abstract class AssembleSite : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val distribution: DirectoryProperty

    @get:Input
    abstract val version: Property<String>

    @get:OutputDirectory
    abstract val site: DirectoryProperty

    @TaskAction
    fun assemble() {
        val out = site.get().asFile
        out.deleteRecursively()
        distribution.get().asFile.copyRecursively(out)
        out.walkTopDown().filter { it.isFile && it.name.endsWith(".map") }.forEach { it.delete() }
        val stamped = setOf("index.html", "sw.js")
        fun files() = out.walkTopDown().filter { it.isFile }
            .map { it.relativeTo(out).invariantSeparatorsPath to it }
            .filter { (path, _) -> path != MANIFEST }
            .sortedBy { it.first }
            .toList()
        // The build id covers every file as built (index.html and sw.js before stamping).
        val build = sha256(
            files().joinToString("\n") { (path, file) ->
                "$path:${sha256(file.readBytes())}"
            }.toByteArray(),
        )
            .take(BUILD_ID_LENGTH)
        stamped.forEach { name ->
            val file = out.resolve(name)
            file.writeText(file.readText().replace("__GOA_BUILD__", build).replace("__GOA_VERSION__", version.get()))
        }
        val entries = files().filter { (path, _) -> path != "sw.js" }.joinToString(",\n") { (path, file) ->
            val hash = sha256(file.readBytes()).take(HASH_LENGTH)
            """    {"p": "${path.replace("\"", "\\\"")}", "s": ${file.length()}, "h": "$hash"}"""
        }
        out.resolve(MANIFEST).writeText(
            "{\n  \"build\": \"$build\",\n  \"version\": \"${version.get()}\",\n  \"files\": [\n$entries\n  ]\n}\n",
        )
        logger.lifecycle("Web site: build $build, version ${version.get()} → $out")
    }

    private fun sha256(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    private companion object {
        const val MANIFEST = "asset-manifest.json"
        const val BUILD_ID_LENGTH = 12
        const val HASH_LENGTH = 16
    }
}

/** The Android app's versionName (app/build.gradle.kts), so both say the same version. */
val appVersion: Provider<String> = providers.fileContents(
    rootProject.layout.projectDirectory.file("app/build.gradle.kts"),
)
    .asText.map { Regex("""versionName\s*=\s*"([^"]+)"""").find(it)?.groupValues?.get(1) ?: "dev" }

val site = tasks.register<AssembleSite>("site") {
    group = "web"
    description = "Builds the deployable web app (GitHub Pages) into build/site."
    dependsOn("jsBrowserDistribution")
    distribution.set(layout.buildDirectory.dir("dist/js/productionExecutable"))
    version.set(appVersion)
    site.set(layout.buildDirectory.dir("site"))
}

// Playwright end-to-end tests against build/site (web/e2e; run `npm ci` there once).
tasks.register<Exec>("webE2e") {
    group = "web"
    description = "Runs the Playwright suite (WebKit iPhone 15 + Chromium Pixel 7) against the built site."
    dependsOn(site)
    val e2e = rootProject.file("web/e2e")
    workingDir = e2e
    val windows = System.getProperty("os.name").lowercase().contains("windows")
    commandLine(if (windows) listOf("cmd", "/c", "npx", "playwright", "test") else listOf("npx", "playwright", "test"))
    environment("GOA_SITE_DIR", layout.buildDirectory.dir("site").get().asFile.absolutePath)
}

