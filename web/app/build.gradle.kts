/**
 * The UI icons as inline SVG markup (`IconMarkup.kt`), generated from the SVG files: the web-only
 * icons in `src/jsMain/resources/icons` and the tab icons in `design/icons`. Inline SVG tints with
 * `currentColor`, needs no request and has no first-paint gap (CSS masks on the sticky/fixed bars
 * weren't repainted by WebKit once they loaded).
 */
abstract class GenerateIconMarkup : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val icons: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val entries = icons.files.filter { it.extension == "svg" }.sortedBy { it.name }.joinToString(",\n") { file ->
            val markup = file.readText()
                .replace(Regex("<title>.*?</title>", RegexOption.DOT_MATCHES_ALL), "")
                .replace(Regex("""\s(width|height)="[^"]*""""), "")
                .replace("#FFFFFF", "currentColor")
                .replace("<svg ", "<svg aria-hidden=\"true\" focusable=\"false\" ")
                .lines().joinToString("") { it.trim() }
                .replace("$", "")
            "        \"${file.nameWithoutExtension}\" to \"\"\"$markup\"\"\""
        }
        val dir = output.get().asFile.resolve("dev/quinton/goa/web/ui")
        dir.mkdirs()
        dir.resolve("IconMarkup.kt").writeText(
            "// Generated by :web:app:iconMarkup from the icon SVG files. Do not edit.\n" +
                "package dev.quinton.goa.web.ui\n\n" +
                "internal val IconMarkup: Map<String, String> = mapOf(\n$entries,\n)\n",
        )
    }
}

val iconMarkup = tasks.register<GenerateIconMarkup>("iconMarkup") {
