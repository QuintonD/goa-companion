package dev.quinton.goa.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Writes the `*.[extension]` files of [sourceDir] into a Kotlin object, `[objectName].text(name)`,
 * so shared (multiplatform) code reads what used to be classpath resources on every platform,
 * the browser included (ADR-043). The files stay the source of truth; this runs before compiling.
 */
@CacheableTask
abstract class EmbedTextFiles : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sourceDir: DirectoryProperty

    @get:Input
    abstract val extension: Property<String>

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val objectName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val files = sourceDir.get().asFile.listFiles { f -> f.isFile && f.extension == extension.get() }
            .orEmpty().sortedBy { it.name }
        val pkg = packageName.get()
        val out = outputDir.get().asFile
        out.deleteRecursively()
        val target = out.resolve(pkg.replace('.', '/')).resolve("${objectName.get()}.kt")
        target.parentFile.mkdirs()
        target.writeText(
            buildString {
                append("// Generated by EmbedTextFiles from ${sourceDir.get().asFile.name}/*.${extension.get()}. Do not edit.\n")
                append("package $pkg\n\n")
                append("internal object ${objectName.get()} {\n")
                append("    /** The file names, without the extension, sorted. */\n")
                append("    val names: List<String> = listOf(")
                append(files.joinToString(", ") { literal(it.nameWithoutExtension) })
                append(")\n\n")
                append("    /** The text of `<name>.${extension.get()}`, or null when there is no such file. */\n")
                append("    fun text(name: String): String? = when (name) {\n")
                files.forEach { f ->
                    append("        ${literal(f.nameWithoutExtension)} -> ${literal(f.readText().replace("\r\n", "\n"))}\n")
                }
                append("        else -> null\n")
                append("    }\n")
                append("}\n")
            },
        )
    }

    private fun literal(text: String): String = buildString {
        append('"')
        text.forEach { c ->
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                else -> append(c)
            }
        }
        append('"')
    }
}
